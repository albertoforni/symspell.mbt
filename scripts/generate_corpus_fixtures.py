#!/usr/bin/env python3
"""Generate offline corpus tokenization fixtures using symspellpy 6.10.0.

Inputs are already lowercase to isolate token boundaries from this library's
explicit casing policy. Only regeneration requires symspellpy; run `moon fmt`
afterwards. Samples use characters assigned before Unicode 15.0 so fixtures
are reproducible across supported Python versions.
"""

from __future__ import annotations

from importlib.metadata import version
from pathlib import Path
import json
import random
import re

from symspellpy import SymSpell

ROOT = Path(__file__).resolve().parents[1]
REFERENCE_VERSION = "6.10.0"
SEED = 20261016


def literal(value: str) -> str:
    return re.sub(r"\\u([0-9a-f]{4})", r"\\u{\1}", json.dumps(value, ensure_ascii=False))


def main() -> None:
    if version("symspellpy") != REFERENCE_VERSION:
        raise SystemExit(f"Use symspellpy=={REFERENCE_VERSION} for reproducible fixtures")
    samples = [
        "", " \t\r\n\u2003\u00a0", "one", "one one two one",
        "abc abc-def abc_def abc'def abc qwe qwe1 1qwe q1we 1234 1234",
        "don't rock’n’roll 'quoted' dogs’ ' ’’ l’amour ‘quoted’",
        "café déjà-vu naïve groß ǅ ǆ", "東京、京都。中文_漢字", "привет мир—κόσμος",
        "العربية עברית हिन्दी ไทย", "𐐨 𠀀 𞤢", "123 ٣٤ ²½ⅻ ① Ａ１".lower(),
        "é e\u0301 a\u0308b \u0301 only\u0301marks", "👩‍💻hello😀world😃",
        "\ufefffirst\r\nsecond\tthird\u2003fourth", "one\x00two\x01three\x7ffour",
        "a\u200db\u200cc\u200bd\u2060e", "a\ue000b\u0378c\U0010ffffd",
        "''__’’..._", "foo@example.com https://example.org/path?q=term",
    ]
    samples = [text.lower() for text in samples]
    rng = random.Random(SEED)
    alphabet = "abé東𠀀٣²ⅻ'’_-,. \t\n\u0301\u200d😀"
    samples += [
        "".join(rng.choices(alphabet, k=rng.randrange(1, 100)))
        for _ in range(32)
    ]
    output = [
        "// Generated by scripts/generate_corpus_fixtures.py; do not edit.",
        f"// Reference: symspellpy {REFERENCE_VERSION}; random seed {SEED}.",
        "// Inputs are already lowercase; casing policy is tested separately.",
        "", "///|",
        "fn reference_corpus_tokens() -> Array[(String, Array[String])] {", "  [",
    ]
    for text in samples:
        tokens = SymSpell._parse_words(text)
        assert text == text.lower()
        words = ", ".join(literal(token) for token in tokens)
        output.append(f"    ({literal(text)}, [{words}]),")
    output += ["  ]", "}"]
    for threshold in [0, 1, 3, 10]:
        output += [
            "", "///|", f'test "reference corpus tokenization threshold {threshold}" {{',
            f"  let dictionary = @symspell.SymSpell::new(count_threshold={threshold}L)",
            f"  let expected = @symspell.SymSpell::new(count_threshold={threshold}L)",
            "  for round = 0; round < 2; round = round + 1 {",
            "    for fixture in reference_corpus_tokens() {",
            "      let (text, tokens) = fixture",
            "      let mut added_words = 0",
            "      for token in tokens {",
            "        if expected.create_dictionary_entry(token, 1L) {",
            "          added_words = added_words + 1", "        }", "      }",
            "      assert_eq(dictionary.create_dictionary(text), { parsed_tokens: tokens.length(), added_words })",
            "      assert_eq(dictionary.to_snapshot(), expected.to_snapshot())",
            "    }", "  }", "}",
        ]
    (ROOT / "corpus_compatibility_test.mbt").write_text("\n".join(output) + "\n", encoding="utf-8")
    print(f"Generated {len(samples)} corpus samples, tested in {len(samples) * 8} incremental builds.")


if __name__ == "__main__":
    main()
