#!/usr/bin/env python3
"""Generate corpus letter/number ranges from the pinned Unicode 16.0 database.

Uses only Python's standard library. Downloads the checksum-verified source,
or accepts an existing copy with --unicode-data. Run `moon fmt` afterwards.
Normal library builds and tests use the checked-in table without network I/O.
"""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
from urllib.request import urlopen

ROOT = Path(__file__).resolve().parents[1]
UNICODE_VERSION = "16.0.0"
SOURCE = f"https://www.unicode.org/Public/{UNICODE_VERSION}/ucd/UnicodeData.txt"
SOURCE_SHA256 = "ff58e5823bd095166564a006e47d111130813dcf8bf234ef79fa51a870edb48f"


def alphanumeric_ranges(data: str) -> list[tuple[int, int]]:
    ranges: list[tuple[int, int]] = []
    pending: tuple[int, str, str] | None = None
    for line in data.splitlines():
        fields = line.split(";")
        code, name, category = int(fields[0], 16), fields[1], fields[2]
        if name.endswith(", First>"):
            assert pending is None
            pending = code, name.removesuffix(", First>"), category
            continue
        first = code
        if name.endswith(", Last>"):
            assert pending is not None
            first, range_name, range_category = pending
            assert name.removesuffix(", Last>") == range_name
            assert category == range_category and first <= code
            pending = None
        else:
            assert pending is None
        if category[0] not in "LN" or code < 128:
            continue
        if ranges and ranges[-1][1] + 1 == first:
            ranges[-1] = ranges[-1][0], code
        else:
            assert not ranges or ranges[-1][1] < first
            ranges.append((first, code))
    assert pending is None
    return ranges


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--unicode-data", type=Path, help="local UnicodeData.txt")
    args = parser.parse_args()
    if args.unicode_data:
        source = args.unicode_data.read_bytes()
    else:
        with urlopen(SOURCE, timeout=30) as response:
            source = response.read()
    if hashlib.sha256(source).hexdigest() != SOURCE_SHA256:
        raise SystemExit("UnicodeData.txt does not match the pinned SHA-256")
    ranges = alphanumeric_ranges(source.decode("utf-8"))
    output = [
        "// Generated by scripts/generate_corpus_unicode.py; do not edit.",
        f"// Unicode {UNICODE_VERSION}, general categories L* and N*, excluding ASCII.",
        f"// Source: {SOURCE}",
        f"// SHA-256: {SOURCE_SHA256}",
        "// Copyright © 1991-2026 Unicode, Inc. See UNICODE-LICENSE.txt.",
        "", "///|",
        "let corpus_alphanumeric_ranges : ReadOnlyArray[(Int, Int)] = [",
    ]
    output += [f"  (0x{first:X}, 0x{last:X})," for first, last in ranges]
    output.append("]")
    (ROOT / "corpus_unicode.mbt").write_text("\n".join(output) + "\n", encoding="utf-8")
    print(f"Generated {len(ranges)} non-ASCII Unicode {UNICODE_VERSION} ranges.")


if __name__ == "__main__":
    main()
