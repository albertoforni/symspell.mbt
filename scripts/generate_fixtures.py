#!/usr/bin/env python3
"""Generate offline MoonBit conformance fixtures using symspellpy 6.10.0.

Install requirements-dev.txt, run this script, then run `moon fmt`.
Only fixture regeneration needs Python; normal MoonBit tests are self-contained.
"""

from __future__ import annotations

from importlib.metadata import version
from itertools import product
from pathlib import Path
import json
import random

from symspellpy import SymSpell, Verbosity
from symspellpy.editdistance import DistanceAlgorithm, EditDistance

ROOT = Path(__file__).resolve().parents[1]
REFERENCE_VERSION = "6.10.0"
SEED = 20261014


def string_literal(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def all_words(alphabet: str, max_length: int) -> list[str]:
    return [
        "".join(chars)
        for length in range(max_length + 1)
        for chars in product(alphabet, repeat=length)
    ]


def osa_oracle(left: str, right: str) -> int:
    """Full-matrix specification, independent of either optimized implementation."""
    matrix = [[0] * (len(right) + 1) for _ in range(len(left) + 1)]
    for i in range(len(left) + 1):
        matrix[i][0] = i
    for j in range(len(right) + 1):
        matrix[0][j] = j
    for i in range(1, len(left) + 1):
        for j in range(1, len(right) + 1):
            matrix[i][j] = min(
                matrix[i - 1][j] + 1,
                matrix[i][j - 1] + 1,
                matrix[i - 1][j - 1] + (left[i - 1] != right[j - 1]),
            )
            if (
                i > 1
                and j > 1
                and left[i - 1] == right[j - 2]
                and left[i - 2] == right[j - 1]
            ):
                matrix[i][j] = min(matrix[i][j], matrix[i - 2][j - 2] + 1)
    return matrix[-1][-1]


def score_key(item: tuple[str, int, int]) -> tuple[int, int, bytes]:
    # MoonBit String comparison follows UTF-16 order. Upstream leaves exact
    # score ties unspecified; this port resolves them deterministically.
    term, distance, count = item
    return distance, -count, term.encode("utf-16-be")


def lookup_cases() -> tuple[str, int]:
    rng = random.Random(SEED)
    alphabet = "abé東京😀𐐀"
    terms = list(dict.fromkeys(
        all_words("ab", 3)
        + ["members", "remember", "bank", "bink", "CA", "ABC", "café", "é", "👩‍💻", "\ufffd"]
        + ["".join(rng.choices(alphabet, k=rng.randrange(1, 11))) for _ in range(35)]
        + ["abcdefgh", "abcdefgi", "abcxyzgh"]
    ))
    entries = [(term, rng.randrange(0, 31)) for term in terms]
    queries = list(dict.fromkeys(
        all_words("ab", 4)
        + terms
        + ["memebers", "knab", "bnak", "xban", "É", "😀a", "東亰"]
        + ["".join(rng.choices(alphabet, k=rng.randrange(0, 12))) for _ in range(30)]
    ))
    output = [
        "// Generated by scripts/generate_fixtures.py; do not edit.",
        f"// Reference: symspellpy {REFERENCE_VERSION}; random seed {SEED}.",
        "// Expected sets are also verified against an exhaustive OSA oracle.",
    ]
    total = 0
    for maximum in range(5):
        for prefix in sorted({maximum + 1, 7}):
            for threshold in [0, 10]:
                reference = SymSpell(maximum, prefix, threshold)
                for term, count in entries:
                    reference.create_dictionary_entry(term, count)
                name = f"reference lookup distance {maximum} prefix {prefix} threshold {threshold}"
                output += [
                    "", "///|", f"test {string_literal(name)} {{",
                    "  let dictionary = @symspell.SymSpell::new(",
                    f"    max_dictionary_edit_distance={maximum},",
                    f"    prefix_length={prefix},",
                    f"    count_threshold={threshold}L,", "  )",
                    "  let entries : Array[(String, Int64)] = [",
                ]
                output += [f"    ({string_literal(term)}, {count}L)," for term, count in entries]
                output += [
                    "  ]", "  for entry in entries {",
                    "    let (term, count) = entry",
                    "    let _ = dictionary.create_dictionary_entry(term, count)",
                    "  }",
                    "  let cases : Array[(String, Int, Array[(String, Int, Int64)])] = [",
                ]
                for query in queries:
                    exhaustive = [
                        (term, osa_oracle(query, term), count)
                        for term, count in reference.words.items()
                    ]
                    for limit in range(maximum + 1):
                        raw = [
                            (item.term, item.distance, item.count)
                            for item in reference.lookup(query, Verbosity.ALL, limit)
                        ]
                        # The Python reference can emit a one-character term
                        # twice, including at a larger distance through the
                        # empty deletion key. Keep its best-distance result.
                        unique = {}
                        for item in raw:
                            if item[0] not in unique or score_key(item) < score_key(unique[item[0]]):
                                unique[item[0]] = item
                        expected = sorted(unique.values(), key=score_key)
                        oracle = sorted([
                            item for item in exhaustive if item[1] <= limit
                        ], key=score_key)
                        if expected != oracle:
                            raise AssertionError((name, query, limit, expected, oracle))
                        suggestions = ", ".join(
                            f"({string_literal(term)}, {distance}, {count}L)"
                            for term, distance, count in expected
                        )
                        output.append(f"    ({string_literal(query)}, {limit}, [{suggestions}]),")
                        total += 1
                output += [
                    "  ]", "  for fixture in cases {",
                    "    let (query, limit, expected) = fixture",
                    "    let all = dictionary.lookup(query, verbosity=All, max_edit_distance=limit)",
                    "    assert_eq(all.map(item => (item.term, item.distance, item.count)), expected)",
                    "    let closest = if expected.is_empty() { [] } else {",
                    "      expected.filter(item => item.1 == expected[0].1)",
                    "    }",
                    "    let top = if expected.is_empty() { [] } else { [expected[0]] }",
                    "    let actual_closest = dictionary.lookup(query, max_edit_distance=limit)",
                    "    let actual_top = dictionary.lookup(query, verbosity=Top, max_edit_distance=limit)",
                    "    assert_eq(actual_closest.map(item => (item.term, item.distance, item.count)), closest)",
                    "    assert_eq(actual_top.map(item => (item.term, item.distance, item.count)), top)",
                    "    if expected.is_empty() {",
                    "      let fallback = dictionary.lookup(query, max_edit_distance=limit, include_unknown=true)",
                    "      assert_eq(fallback.map(item => (item.term, item.distance, item.count)), [(query, limit + 1, 0L)])",
                    "    }", "  }", "}",
                ]
    return "\n".join(output) + "\n", total


def distance_cases() -> tuple[str, int]:
    terms = all_words("ab😀", 4)
    reference = EditDistance(DistanceAlgorithm.DAMERAU_OSA)
    distances = []
    for left in terms:
        for right in terms:
            distance = reference.compare(left, right, 4)
            if distance != osa_oracle(left, right):
                raise AssertionError((left, right, distance))
            distances.append(distance)
    output = [
        "// Generated by scripts/generate_fixtures.py; do not edit.",
        f"// Reference: symspellpy {REFERENCE_VERSION}, checked against the OSA specification.",
        "", "///|", 'test "banded distance matches the exhaustive Unicode reference matrix" {',
        "  let terms : Array[String] = [",
    ]
    output += [f"    {string_literal(term)}," for term in terms]
    output += ["  ]", "  let distances : Array[Int] = ["]
    for start in range(0, len(distances), 24):
        output.append("    " + ", ".join(map(str, distances[start:start + 24])) + ",")
    output += [
        "  ]",
        "  for i = 0; i < terms.length(); i = i + 1 {",
        "    for j = 0; j < terms.length(); j = j + 1 {",
        "      let distance = distances[i * terms.length() + j]",
        "      for limit = 0; limit <= 4; limit = limit + 1 {",
        "        let expected = if distance <= limit { Some(distance) } else { None }",
        "        assert_eq(osa_distance(terms[i].to_array(), terms[j].to_array(), limit), expected)",
        "      }", "    }", "  }", "}",
    ]
    return "\n".join(output) + "\n", len(distances) * 5


def main() -> None:
    installed = version("symspellpy")
    if installed != REFERENCE_VERSION:
        raise SystemExit(f"Install symspellpy=={REFERENCE_VERSION}; found {installed}")
    lookup, lookup_count = lookup_cases()
    distance, distance_count = distance_cases()
    (ROOT / "compatibility_test.mbt").write_text(lookup, encoding="utf-8")
    (ROOT / "distance_reference_wbtest.mbt").write_text(distance, encoding="utf-8")
    print(f"Generated {lookup_count} lookup cases (all three modes) and {distance_count} distance/cutoff checks.")


if __name__ == "__main__":
    main()
