#!/usr/bin/env python3
"""Generate phrase fixtures from symspellpy 6.10.0 using synthetic dictionaries.

Compound fixtures use upstream's whitespace tokenization. Segmentation fixtures
use inputs without whitespace, NFKC changes, or case changes; whitespace fixes
and explicit normalization policy have separate hand-written regressions.
"""

from __future__ import annotations

from importlib.metadata import version
from pathlib import Path
import json
import random

from symspellpy import SymSpell, Verbosity

ROOT = Path(__file__).resolve().parents[1]
REFERENCE_VERSION = "6.10.0"
SEED = 20261015


def literal(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


class CanonicalSymSpell(SymSpell):
    """Resolve single-word score ties with the port's documented lexical policy."""

    def lookup(self, phrase, verbosity, max_edit_distance=None, *args, **kwargs):
        raw = super().lookup(phrase, Verbosity.ALL, max_edit_distance, *args, **kwargs)
        unique = {}
        for item in raw:
            current = unique.get(item.term)
            if current is None or item.distance < current.distance:
                unique[item.term] = item
        suggestions = sorted(
            unique.values(),
            key=lambda item: (item.distance, -item.count, item.term.encode("utf-16-be")),
        )
        if verbosity == Verbosity.TOP:
            return suggestions[:1]
        if verbosity == Verbosity.CLOSEST and suggestions:
            return [item for item in suggestions if item.distance == suggestions[0].distance]
        return suggestions


def corrupt(text: str, rng: random.Random) -> str:
    if not text:
        return text
    position = rng.randrange(len(text))
    operation = rng.randrange(4)
    if operation == 0:
        return text[:position] + text[position + 1:]
    if operation == 1:
        return text[:position] + "x" + text[position + 1:]
    if operation == 2:
        return text[:position] + "z" + text[position:]
    if position + 1 < len(text):
        return text[:position] + text[position + 1] + text[position] + text[position + 2:]
    return text


def setup(output: list[str], entries, bigrams, maximum: int, corpus: int) -> None:
    output += [
        "  let dictionary = @symspell.SymSpell::new(",
        f"    max_dictionary_edit_distance={maximum},",
        f"    prefix_length={maximum + 1},",
        f"    corpus_size={corpus}L,", "  )",
    ]
    for term, count in entries:
        output.append(f"  let _ = dictionary.create_dictionary_entry({literal(term)}, {count}L)")
    for term, count in bigrams:
        output.append(f"  let _ = dictionary.set_bigram_count({literal(term)}, {count}L)")


def main() -> None:
    if version("symspellpy") != REFERENCE_VERSION:
        raise SystemExit(f"Install symspellpy=={REFERENCE_VERSION}")
    rng = random.Random(SEED)
    datasets = {
        "english": "a is where whereas steam machine hello world the quick brown fox jumps over lazy dog ice cream don't can't some words members remember".split(),
        "unicode": ["東京", "大阪", "京都", "旅行", "café", "été", "😀", "😃", "𐐨", "ab", "abc", "!", "'s"],
    }
    output = [
        "// Generated by scripts/generate_phrase_fixtures.py; do not edit.",
        f"// Reference: symspellpy {REFERENCE_VERSION}; seed {SEED}.",
        "// Single-word ties are canonicalized to the port's lexical policy.",
        "// Segmentation whitespace regressions are tested in phrase_test.mbt.",
    ]
    compound_count = 0
    segmentation_count = 0
    for name, words in datasets.items():
        entries = [(word, 1000 - index * 17) for index, word in enumerate(words)]
        pairs = list(dict.fromkeys(
            ["where is", "hello world", "ice cream"] if name == "english"
            else ["東京 旅行", "大阪 京都", "café été"]
        ))
        bigrams = [(pair, 300 + index * 47) for index, pair in enumerate(pairs)]
        phrases = ["", "unknown", *words]
        compact = list(words)
        for _ in range(35):
            sequence = [rng.choice(words) for _ in range(rng.randrange(1, 4))]
            clean = " ".join(sequence)
            joined = "".join(sequence)
            phrases += [clean, clean.replace(" ", "", 1), corrupt(clean, rng)]
            compact += [joined, corrupt(joined, rng)]
        if name == "english":
            phrases += ["whereiz", "whereis", "ste am machie", "qwer erty ytui a", "hello  world"]
            compact += ["thequickbrownfoxjumpsoverthelazydog", "helloworld", "unknownword"]
        phrases = list(dict.fromkeys(phrases))
        compact = [phrase for phrase in dict.fromkeys(compact) if phrase]
        longest = max(map(len, words))
        for maximum in range(3):
            for corpus in [1024908267229, 10000]:
                for contextual in [False, True]:
                    reference = CanonicalSymSpell(maximum, maximum + 1)
                    reference.N = corpus
                    for term, count in entries:
                        reference.create_dictionary_entry(term, count)
                    active_bigrams = bigrams if contextual else []
                    for term, count in active_bigrams:
                        reference.bigrams[term] = count
                    if active_bigrams:
                        reference.bigram_count_min = min(count for _, count in active_bigrams)
                    label = f"reference compound {name} distance {maximum} corpus {corpus} bigrams {contextual}"
                    output += ["", "///|", f"test {literal(label)} {{"]
                    setup(output, entries, active_bigrams, maximum, corpus)
                    output.append("  let fixtures : Array[(String, Int, String, Int, Int64)] = [")
                    for phrase in phrases:
                        for limit in range(maximum + 1):
                            expected = reference.lookup_compound(phrase, limit, split_by_space=True)[0]
                            output.append(
                                f"    ({literal(phrase)}, {limit}, {literal(expected.term)}, {expected.distance}, {expected.count}L),"
                            )
                            compound_count += 1
                    output += [
                        "  ]", "  for fixture in fixtures {",
                        "    let (phrase, limit, term, distance, count) = fixture",
                        "    let result = dictionary.lookup_compound(phrase, max_edit_distance=limit)",
                        "    assert_eq(result.length(), 1)",
                        "    assert_eq((result[0].term, result[0].distance, result[0].count), (term, distance, count))",
                        "  }", "}",
                    ]
                    if contextual:
                        continue
                    label = f"reference segmentation {name} distance {maximum} corpus {corpus}"
                    output += ["", "///|", f"test {literal(label)} {{"]
                    setup(output, entries, [], maximum, corpus)
                    output.append("  let fixtures : Array[(String, Int, Int, String, String, Int, Double)] = [")
                    for phrase in compact:
                        for limit in range(maximum + 1):
                            for window in sorted({1, longest}):
                                result = reference.word_segmentation(phrase, limit, window)
                                output.append(
                                    f"    ({literal(phrase)}, {limit}, {window}, {literal(result.segmented_string)}, "
                                    f"{literal(result.corrected_string)}, {result.distance_sum}, {result.log_prob_sum:.9f}),"
                                )
                                segmentation_count += 1
                    output += [
                        "  ]", "  for fixture in fixtures {",
                        "    let (phrase, limit, window, segmented, corrected, distance, probability) = fixture",
                        "    let result = dictionary.word_segmentation(phrase, max_edit_distance=limit, max_segmentation_word_length=window)",
                        "    assert_eq((result.segmented_string, result.corrected_string, result.distance_sum), (segmented, corrected, distance))",
                        "    assert_true((result.log_prob_sum - probability).abs() < 0.000000001)",
                        "  }", "}",
                    ]
    (ROOT / "phrase_compatibility_test.mbt").write_text("\n".join(output) + "\n", encoding="utf-8")
    print(f"Generated {compound_count} compound and {segmentation_count} segmentation cases.")


if __name__ == "__main__":
    main()
