#!/usr/bin/env python3
"""Generate format-v1 byte fixtures with Python's standard library.

This encoder independently follows docs/snapshot-format.md, enumerates Unicode
subsequences with itertools, orders terms by UTF-16 code units, and uses zlib's
CRC32. It requires neither MoonBit nor symspellpy.
"""

from __future__ import annotations

from itertools import combinations, product
from pathlib import Path
import json
import struct
import zlib

ROOT = Path(__file__).resolve().parents[1]
MAX_FREQUENCY = (1 << 63) - 1


def ordered(terms):
    return sorted(terms, key=lambda term: term.encode("utf-16-be"))


def string(term: str) -> bytes:
    encoded = term.encode("utf-8")
    return struct.pack("<I", len(encoded)) + encoded


def frequencies(entries: dict[str, int]) -> bytes:
    return struct.pack("<I", len(entries)) + b"".join(
        string(term) + struct.pack("<q", entries[term]) for term in ordered(entries)
    )


def encode_snapshot(distance, prefix_length, threshold, corpus, words, pending, bigrams):
    terms = ordered(words)
    buckets: dict[str, list[int]] = {}
    for word_id, term in enumerate(terms):
        prefix = term[:prefix_length]
        variants = {
            "".join(prefix[index] for index in selected)
            for length in range(max(0, len(prefix) - distance), len(prefix) + 1)
            for selected in combinations(range(len(prefix)), length)
        }
        for key in variants:
            buckets.setdefault(key, []).append(word_id)
    payload = (
        b"MBSSIDX\x00"
        + struct.pack("<IIIqq", 1, distance, prefix_length, threshold, corpus)
        + frequencies(words)
        + frequencies(pending)
        + frequencies(bigrams)
        + struct.pack("<I", len(buckets))
    )
    for key in ordered(buckets):
        ids = buckets[key]
        payload += string(key) + struct.pack("<I", len(ids))
        payload += struct.pack(f"<{len(ids)}I", *ids)
    return payload + struct.pack("<I", zlib.crc32(payload))


def literal(value: str) -> str:
    # MoonBit accepts JSON-style escapes except for the NUL escape form.
    return json.dumps(value, ensure_ascii=False).replace("\\u0000", "\\u{0000}")


def byte_literal(data: bytes) -> str:
    return 'b"' + "".join(f"\\x{byte:02x}" for byte in data) + '"'


def main() -> None:
    unicode_terms = [
        "", "café", "e\u0301", "É", "東京", "АБИ", "a😀", "𐐀", "\ue000",
        "👩‍💻", "\ufeffbom", "line\nfeed", "tab\tword", "null\x00word",
        'quote"slash\\word', "has spaces", "aaaa", "abab",
    ]
    alphabet = [""] + [
        "".join(chars) for length in range(1, 4)
        for chars in product("ab😀", repeat=length)
    ]
    cases = [
        ("empty", 2, 7, 1, 1024908267229, {}, {}, {}),
        ("empty extreme counts", 0, 2147483647, MAX_FREQUENCY, MAX_FREQUENCY, {}, {}, {}),
        ("pending only", 2, 3, MAX_FREQUENCY, 10000, {}, {"": 1, "café": 5, "😀": MAX_FREQUENCY - 1}, {}),
        ("zero word and bigram frequencies", 0, 1, 0, 1, {"": 0, "hello": 0, "world": MAX_FREQUENCY}, {}, {"hello world": 0}),
        ("unicode and exact Int64 counts", 2, 7, 0, MAX_FREQUENCY,
         {term: MAX_FREQUENCY - i for i, term in enumerate(unicode_terms)}, {}, {"東京 😀": MAX_FREQUENCY, "café été": 0}),
    ]
    for distance in range(5):
        for prefix in [distance + 1, 7]:
            for threshold in [0, 3]:
                counts = {term: i % 7 for i, term in enumerate(alphabet)}
                words = {term: count for term, count in counts.items() if count >= threshold}
                pending = {term: count for term, count in counts.items() if 0 < count < threshold}
                cases.append((
                    f"distance {distance} prefix {prefix} threshold {threshold}",
                    distance, prefix, threshold, 10000, words, pending, {"a b": 7, "😀 a": 2},
                ))
    output = [
        "// Generated by scripts/generate_snapshot_fixtures.py; do not edit.",
        "// Independent Python struct/itertools/zlib encoder; binary format v1.",
        "", "///|", "fn snapshot_fixture_bytes(chunks : Array[Bytes]) -> Bytes {",
        "  Bytes::from_iter(chunks.iter().flat_map(Bytes::iter))", "}",
    ]
    for name, distance, prefix, threshold, corpus, words, pending, bigrams in cases:
        snapshot = encode_snapshot(distance, prefix, threshold, corpus, words, pending, bigrams)
        output += [
            "", "///|", f"test {literal('snapshot format fixture ' + name)} {{",
            "  let dictionary = @symspell.SymSpell::new(",
            f"    max_dictionary_edit_distance={distance},",
            f"    prefix_length={prefix},", f"    count_threshold={threshold}L,",
            f"    corpus_size={corpus}L,", "  )",
        ]
        # Reverse insertion order verifies that the writer canonicalizes tables.
        for term in reversed(ordered(words)):
            output.append(f"  let _ = dictionary.create_dictionary_entry({literal(term)}, {words[term]}L)")
        for term in reversed(ordered(pending)):
            output.append(f"  let _ = dictionary.create_dictionary_entry({literal(term)}, {pending[term]}L)")
        for term in reversed(ordered(bigrams)):
            output.append(f"  let _ = dictionary.set_bigram_count({literal(term)}, {bigrams[term]}L)")
        output += ["  let fixture = snapshot_fixture_bytes(["]
        output += [f"    {byte_literal(snapshot[offset:offset + 32])}," for offset in range(0, len(snapshot), 32)]
        output += [
            "  ])", "  assert_eq(dictionary.to_snapshot(), fixture)",
            "  let restored = @symspell.SymSpell::from_snapshot(fixture)",
            "  assert_eq(restored.to_snapshot(), fixture)",
            "  assert_eq(restored.word_count(), dictionary.word_count())",
            "  assert_eq(restored.pending_word_count(), dictionary.pending_word_count())",
            "  assert_eq(restored.entry_count(), dictionary.entry_count())",
            "  assert_eq(restored.bigram_count(), dictionary.bigram_count())",
        ]
        for query in ["", "a", "b", "😀", "ba", "cafe", "東亰", "unknown"]:
            output += [
                f"  assert_eq(restored.lookup({literal(query)}, verbosity=All), dictionary.lookup({literal(query)}, verbosity=All))",
            ]
        output += ["}"]
    destination = ROOT / "snapshot_compatibility_test.mbt"
    destination.write_text("\n".join(output) + "\n")
    print(f"Wrote {len(cases)} independent format-v1 fixtures to {destination.name}")


if __name__ == "__main__":
    main()
